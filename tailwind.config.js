/* ============================================
   tailwind.config.js — ใช้ตอน build เท่านั้น ไม่ได้ถูกโหลดตอนเปิดเว็บ
   ============================================
   เดิมค่าชุดนี้เป็น <script>tailwind.config = {...}</script> อยู่ใน index.html และทำงานคู่กับ
   cdn.tailwindcss.com ซึ่งคอมไพล์ CSS ใหม่ในเบราว์เซอร์ของผู้ใช้ทุกครั้งที่เปิดหน้า
   ทีมงาน Tailwind เองระบุว่า CDN ตัวนั้นมีไว้ prototype ไม่ใช่สำหรับเว็บที่เปิดใช้จริง เพราะ
     - ต้องโหลด JS ราว 400 KB มาคอมไพล์ก่อน หน้าเว็บจึงแวบเป็นข้อความเปล่าก่อนช่วงหนึ่ง (FOUC)
     - URL ไม่ระบุเวอร์ชัน = เนื้อไฟล์เปลี่ยนเองได้ทุกเมื่อที่ Tailwind ออกรุ่นใหม่ ใส่ SRI ก็ไม่ได้
     - CDN ล่ม = เว็บไม่มีสไตล์เลย ทั้งที่โค้ดเราไม่ได้เปลี่ยนอะไร
     - บังคับให้ CSP ต้องเปิด unsafe-eval ทิ้งไว้ตลอด
   ตอนนี้จึงคอมไพล์ล่วงหน้าเป็น css/tailwind.css แล้ว commit ลง repo — ผู้ใช้ยังเปิด index.html
   ได้เหมือนเดิมโดยไม่ต้อง build อะไร ส่วนคนแก้โค้ดรัน `npm run build:css` เมื่อเพิ่มคลาสใหม่

   สำคัญ: ถ้าเพิ่มคลาส Tailwind ใหม่ในไฟล์ไหนก็ตาม ต้องรัน build ใหม่ ไม่งั้นคลาสนั้นจะไม่มีสไตล์
   มีขั้นตอนเช็คใน CI (.github/workflows/tests.yml) คอยดักไว้ให้แล้วกันลืม
   ============================================ */

