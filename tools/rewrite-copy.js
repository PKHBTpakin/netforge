let applied = 0, missing = [];
const byFile = {};
EDITS.forEach(function ([file, from, to]) {
    (byFile[file] = byFile[file] || []).push([from, to]);
});

Object.keys(byFile).forEach(function (file) {
    const full = path.join(ROOT, file);
    let src = fs.readFileSync(full, 'utf8');
    const before = src;

    byFile[file].forEach(function ([from, to]) {
        if (src.includes(from)) {
            src = src.split(from).join(to);
            applied++;
        } else if (!src.includes(to)) {
            // หาไม่เจอ และยังไม่เคยถูกแทนที่มาก่อน = ข้อความต้นทางเปลี่ยนไปแล้ว ต้องมาดูด้วยตา
            missing.push(file + ': ' + from.slice(0, 60));
        }
    });

    if (src !== before && !CHECK_ONLY) fs.writeFileSync(full, src);
});

console.log((CHECK_ONLY ? 'ตรวจสอบ' : 'แก้ไข') + ' ' + applied + '/' + EDITS.length + ' รายการ');
if (missing.length) {
    console.log('\nหาข้อความเดิมไม่เจอ ' + missing.length + ' รายการ (อาจถูกแก้ไปแล้วหรือพิมพ์ไม่ตรง):');
    missing.forEach(function (m) { console.log('  ' + m); });
}
process.exit(missing.length ? 1 : 0);
